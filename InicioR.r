# Imprimir
print("Welcome to R programming!")


# Variable Numerica
age <- 25
print(age)


# Variable con enteros
count <- 10L
print(count)


# Variable Caracter
name <- "John Doe"
print(name)


# Dato Logico
verdadero <- TRUE
falso <- FALSE
print(verdadero)
print(falso)


# Ausencia de Datos
missing_value <- NA


# Comprobacion de Datos (class())
print("Comprobacion de Datos = class():")

print(class(age))               # Numerico
print(class(count))             # Entero
print(class(name))              # Caracter
print(class(verdadero))         # Logico
print(class(falso))             # Logico
print(class(missing_value))     # Logico

